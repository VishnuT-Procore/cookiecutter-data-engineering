"""Postgres plugin generator: dbt sources, bronze and silver models from config/pipeline.yml.

With streaming_engine=flink it also renders the Flink SQL job (flink/sql/pipeline.sql) and the
Postgres tables it writes (flink/sql/postgres_tables.sql); bronze/silver dbt models then become
views over those tables so gold models and tests stay the same.

Called by scripts/generate.py; see that file for the plugin contract.
"""

from __future__ import annotations

HEADER = "GENERATED by scripts/generate.py from config/pipeline.yml. Do not edit; change the config and run `make generate`."

MANAGED_GLOBS = ["dbt/models/bronze/*", "dbt/models/silver/*", "flink/sql/*"]


def _jinja_list(items: list[str]) -> str:
    return "[" + ", ".join(repr(i) for i in items) + "]"


def _jinja_columns(columns: list[dict]) -> str:
    lines = [f"        {{'name': {c['name']!r}, 'type': {c['type']!r}}}" for c in columns]
    return "[\n" + ",\n".join(lines) + "\n    ]"


def _yaml_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_bronze(entity: dict, payload_format: str) -> str:
    return f"""-- {HEADER}
-- Bronze: every change from topic `{entity['topic']}`, append-only and idempotent on (partition, offset).
{{{{ config(unique_key=['_kafka_partition', '_kafka_offset']) }}}}

{{{{ bronze_model(
    source_table={entity['name']!r},
    payload_format={payload_format!r},
    columns={_jinja_columns(entity['columns'])}
) }}}}
"""


def render_silver(entity: dict) -> str:
    return f"""-- {HEADER}
-- Silver: latest version of each {entity['name']} row (deletes kept as _is_deleted = true).
{{{{ config(unique_key={_jinja_list(entity['primary_key'])}) }}}}

{{{{ silver_model(
    bronze_relation=ref('bronze_{entity['name']}'),
    columns={_jinja_columns(entity['columns'])},
    primary_key={_jinja_list(entity['primary_key'])},
    sequence_by={_jinja_list(entity['sequence_by'])}
) }}}}
"""


def render_view(entity: dict, layer: str) -> str:
    what = "every change" if layer == "bronze" else "the latest version of each row"
    return f"""-- {HEADER}
-- {layer.capitalize()}: {what} of {entity['name']}, maintained continuously by the Flink job (flink/sql/pipeline.sql).
{{{{ config(materialized='view') }}}}

select * from {{{{ source('flink', '{layer}_{entity['name']}') }}}}
"""


def render_flink_sources(pipeline: dict) -> str:
    lines = [
        f"# {HEADER}",
        "version: 2",
        "",
        "sources:",
        "  - name: flink",
        f"    schema: {pipeline['raw_schema']}",
        "    description: Tables written continuously by the Flink streaming job.",
        "    tables:",
    ]
    for e in pipeline["entities"]:
        for layer in ("bronze", "silver"):
            lines += [
                f"      - name: {layer}_{e['name']}",
                f"        description: {_yaml_str(layer.capitalize() + ' table for Kafka topic ' + e['topic'] + '.')}",
            ]
    return "\n".join(lines) + "\n"


def render_sources(pipeline: dict) -> str:
    lines = [
        f"# {HEADER}",
        "version: 2",
        "",
        "sources:",
        "  - name: kafka_raw",
        f"    schema: {pipeline['raw_schema']}",
        "    description: Raw Kafka records landed by ingestion/kafka_to_raw.py (one table per topic).",
        "    tables:",
    ]
    for e in pipeline["entities"]:
        lines += [
            f"      - name: {e['name']}",
            f"        description: {_yaml_str('Raw records from Kafka topic ' + e['topic'] + '.')}",
            "        config:",
            "          meta:",
            f"            topic: {_yaml_str(e['topic'])}",
        ]
    return "\n".join(lines) + "\n"


def _column_docs(entity: dict, indent: str, pk_tests: bool) -> list[str]:
    lines = [f"{indent}columns:"]
    for c in entity["columns"]:
        lines.append(f"{indent}  - name: {c['name']}")
        if c["description"]:
            lines.append(f"{indent}    description: {_yaml_str(c['description'])}")
        if pk_tests and c["name"] in entity["primary_key"]:
            lines.append(f"{indent}    data_tests: [not_null]")
    return lines


def render_schema(pipeline: dict, layer: str) -> str:
    lines = [f"# {HEADER}", "version: 2", "", "models:"]
    for e in pipeline["entities"]:
        if layer == "bronze":
            desc = f"Change log of {e['name']} ({pipeline['payload_format']} payloads). {e['description']}".strip()
            key = ["_kafka_partition", "_kafka_offset"]
        else:
            desc = f"Latest version of each {e['name']} row. {e['description']}".strip()
            key = e["primary_key"]
        lines += [
            f"  - name: {layer}_{e['name']}",
            f"    description: {_yaml_str(desc)}",
            "    data_tests:",
            "      - unique_key_combination:",
            "          arguments:",
            f"            columns: {_jinja_list(key)}",
        ]
        lines += _column_docs(e, "    ", pk_tests=layer == "silver")
        lines.append("")
    return "\n".join(lines)


# --- Flink ---------------------------------------------------------------------------------

FLINK_TYPES = {
    "string": "STRING", "integer": "INT", "bigint": "BIGINT", "double": "DOUBLE", "boolean": "BOOLEAN",
    "date": "DATE", "timestamp": "TIMESTAMP(3)", "timestamp_ms": "TIMESTAMP(3)", "timestamp_us": "TIMESTAMP(3)",
}
POSTGRES_TYPES = {
    "string": "text", "integer": "integer", "bigint": "bigint", "double": "double precision", "boolean": "boolean",
    "date": "date", "timestamp": "timestamp(3)", "timestamp_ms": "timestamp(3)", "timestamp_us": "timestamp(3)",
}
METADATA = [
    ("_op", "STRING", "text"),
    ("_is_deleted", "BOOLEAN", "boolean"),
    ("_source_ts_ms", "BIGINT", "bigint"),
    ("_kafka_topic", "STRING", "text"),
    ("_kafka_partition", "INT", "integer"),
    ("_kafka_offset", "BIGINT", "bigint"),
    ("_kafka_timestamp", "TIMESTAMP(3)", "timestamp(3)"),
    ("_ingested_at", "TIMESTAMP(3)", "timestamp(3)"),
]


def _type(mapping: dict, t: str, decimal: str) -> str:
    return f"{decimal}{t[len('decimal'):]}" if t.startswith("decimal") else mapping[t]


def flink_type(t: str) -> str:
    return _type(FLINK_TYPES, t, "DECIMAL")


def postgres_type(t: str) -> str:
    return _type(POSTGRES_TYPES, t, "numeric")


def flink_field(record: str, name: str, t: str) -> str:
    value = f"JSON_VALUE({record}, '$.{name}')"
    if t == "string":
        return value
    if t == "timestamp":  # ISO-8601 in UTC, e.g. 2024-01-01T00:00:00Z
        return f"CAST(REGEXP_REPLACE(REPLACE({value}, 'T', ' '), '(Z|[+-]00:?00)$', '') AS TIMESTAMP(3))"
    if t == "timestamp_ms":
        return f"CAST(TO_TIMESTAMP_LTZ(CAST({value} AS BIGINT), 3) AS TIMESTAMP(3))"
    if t == "timestamp_us":
        return f"CAST(TO_TIMESTAMP_LTZ(CAST({value} AS BIGINT) / 1000, 3) AS TIMESTAMP(3))"
    return f"CAST({value} AS {flink_type(t)})"


def _flink_records_view(e: dict, payload_format: str) -> str:
    meta = "kafka_topic, kafka_partition, kafka_offset, kafka_timestamp"
    if payload_format == "debezium":
        return f"""-- Debezium envelope; JsonConverter with schemas.enable=true wraps it in {{schema, payload}}.
CREATE TEMPORARY VIEW envelope_{e['name']} AS
SELECT
  CASE WHEN JSON_EXISTS(kafka_value, '$.schema') AND JSON_EXISTS(kafka_value, '$.payload')
       THEN JSON_QUERY(kafka_value, '$.payload') ELSE kafka_value END AS envelope,
  {meta}
FROM kafka_{e['name']}
-- tombstones only exist for log compaction
WHERE kafka_value IS NOT NULL;

CREATE TEMPORARY VIEW records_{e['name']} AS
SELECT
  JSON_VALUE(envelope, '$.op') AS _op,
  CASE WHEN JSON_VALUE(envelope, '$.op') = 'd' THEN JSON_QUERY(envelope, '$.before')
       ELSE JSON_QUERY(envelope, '$.after') END AS record,
  CAST(JSON_VALUE(envelope, '$.ts_ms') AS BIGINT) AS _source_ts_ms,
  {meta}
FROM envelope_{e['name']}
WHERE JSON_VALUE(envelope, '$.op') IN ('c', 'u', 'r', 'd');"""
    return f"""-- Plain JSON rows; a tombstone deletes the key, which is recovered from the JSON message key.
CREATE TEMPORARY VIEW records_{e['name']} AS
SELECT
  CASE WHEN kafka_value IS NULL THEN 'd' ELSE 'u' END AS _op,
  COALESCE(kafka_value, kafka_key) AS record,
  CAST(NULL AS BIGINT) AS _source_ts_ms,
  {meta}
FROM kafka_{e['name']};"""


def _flink_jdbc_sink(name: str, table: str, columns: list[tuple[str, str]], key: list[str]) -> str:
    cols = ",\n".join(f"  `{c}` {t}" for c, t in columns)
    return f"""CREATE TEMPORARY TABLE {name} (
{cols},
  PRIMARY KEY ({', '.join(f'`{k}`' for k in key)}) NOT ENFORCED
) WITH (
  'connector' = 'jdbc',
  'url' = '${{FLINK_JDBC_URL}}',
  'table-name' = '{table}',
  'username' = '${{POSTGRES_USER}}',
  'password' = '${{POSTGRES_PASSWORD}}',
  'sink.buffer-flush.interval' = '1s',
  'sink.buffer-flush.max-rows' = '1000',
  'sink.max-retries' = '3'
);"""


def render_flink_job(pipeline: dict) -> str:
    schema = pipeline["raw_schema"]
    parts = [
        f"-- {HEADER}",
        "-- Placeholders ${...} are filled in from the environment by flink/submit.py.",
        "",
        "SET 'pipeline.name' = '${FLINK_JOB_NAME}';",
        "SET 'execution.checkpointing.interval' = '${FLINK_CHECKPOINT_INTERVAL}';",
        "SET 'table.local-time-zone' = 'UTC';",
        "-- How long per-key state (latest version per key) is kept; 0 = forever.",
        "SET 'table.exec.state.ttl' = '${FLINK_STATE_TTL}';",
    ]
    inserts = []
    for e in pipeline["entities"]:
        name = e["name"]
        entity_cols = [(c["name"], flink_type(c["type"])) for c in e["columns"]]
        all_cols = entity_cols + [(m, t) for m, t, _ in METADATA]
        col_list = ", ".join(f"`{c}`" for c, _ in all_cols)
        typed = ",\n".join(f"  {flink_field('record', c['name'], c['type'])} AS `{c['name']}`" for c in e["columns"])
        pk_present = " AND ".join(f"JSON_VALUE(record, '$.{k}') IS NOT NULL" for k in e["primary_key"])
        order = ", ".join(f"`{c}` DESC" for c in e["sequence_by"])
        parts += [
            "",
            f"-- ===== {name} ({e['topic']}) =====",
            f"""CREATE TEMPORARY TABLE kafka_{name} (
  kafka_key STRING,
  kafka_value STRING,
  kafka_topic STRING METADATA FROM 'topic' VIRTUAL,
  kafka_partition INT METADATA FROM 'partition' VIRTUAL,
  kafka_offset BIGINT METADATA FROM 'offset' VIRTUAL,
  kafka_timestamp TIMESTAMP_LTZ(3) METADATA FROM 'timestamp' VIRTUAL
) WITH (
  'connector' = 'kafka',
  'topic' = '{e['topic']}',
  'properties.bootstrap.servers' = '${{FLINK_KAFKA_BOOTSTRAP_SERVERS}}',
  'properties.group.id' = '${{FLINK_KAFKA_GROUP_ID}}',
  'properties.auto.offset.reset' = 'earliest',
  'scan.startup.mode' = 'group-offsets',
  'key.format' = 'raw',
  'key.fields' = 'kafka_key',
  'value.format' = 'raw',
  'value.fields-include' = 'EXCEPT_KEY'
);""",
            "",
            _flink_records_view(e, pipeline["payload_format"]),
            "",
            f"""CREATE TEMPORARY VIEW changes_{name} AS
SELECT
{typed},
  _op,
  _op = 'd' AS _is_deleted,
  _source_ts_ms,
  kafka_topic AS _kafka_topic,
  kafka_partition AS _kafka_partition,
  kafka_offset AS _kafka_offset,
  CAST(kafka_timestamp AS TIMESTAMP(3)) AS _kafka_timestamp,
  LOCALTIMESTAMP AS _ingested_at
FROM records_{name}
WHERE {pk_present};""",
            "",
            _flink_jdbc_sink(f"sink_bronze_{name}", f"{schema}.bronze_{name}", all_cols, ["_kafka_partition", "_kafka_offset"]),
            "",
            _flink_jdbc_sink(f"sink_silver_{name}", f"{schema}.silver_{name}", all_cols, e["primary_key"]),
        ]
        inserts += [
            f"-- {name}: bronze keeps every change (idempotent upsert on partition/offset).",
            f"INSERT INTO sink_bronze_{name} SELECT {col_list} FROM changes_{name};",
            f"-- {name}: silver keeps the latest change per key; older/replayed events never win.",
            f"""INSERT INTO sink_silver_{name}
SELECT {col_list}
FROM (
  SELECT *, ROW_NUMBER() OVER (PARTITION BY {', '.join(f'`{k}`' for k in e['primary_key'])} ORDER BY {order}) AS rn
  FROM changes_{name}
)
WHERE rn = 1;""",
        ]
    parts += ["", "EXECUTE STATEMENT SET", "BEGIN", *inserts, "END;", ""]
    return "\n".join(parts)


def render_postgres_tables(pipeline: dict) -> str:
    schema = pipeline["raw_schema"]
    parts = [f"-- {HEADER}", "-- Tables written by the Flink job (applied by flink/submit.py).", "",
             f"create schema if not exists {schema};"]
    for e in pipeline["entities"]:
        cols = [(c["name"], postgres_type(c["type"])) for c in e["columns"]] + [(m, p) for m, _, p in METADATA]
        body = ",\n".join(f"    {c} {t}" for c, t in cols)
        for layer, key in (("bronze", ["_kafka_partition", "_kafka_offset"]), ("silver", e["primary_key"])):
            parts += ["", f"create table if not exists {schema}.{layer}_{e['name']} (",
                      body + ",", f"    primary key ({', '.join(key)})", ");"]
    return "\n".join(parts) + "\n"


def render(pipeline: dict) -> dict[str, str]:
    flink = pipeline.get("streaming_engine") == "flink"
    files = {
        "dbt/models/bronze/_sources.yml": render_flink_sources(pipeline) if flink else render_sources(pipeline),
        "dbt/models/bronze/_bronze.yml": render_schema(pipeline, "bronze"),
        "dbt/models/silver/_silver.yml": render_schema(pipeline, "silver"),
    }
    for e in pipeline["entities"]:
        if flink:
            files[f"dbt/models/bronze/bronze_{e['name']}.sql"] = render_view(e, "bronze")
            files[f"dbt/models/silver/silver_{e['name']}.sql"] = render_view(e, "silver")
        else:
            files[f"dbt/models/bronze/bronze_{e['name']}.sql"] = render_bronze(e, pipeline["payload_format"])
            files[f"dbt/models/silver/silver_{e['name']}.sql"] = render_silver(e)
    if flink:
        files["flink/sql/pipeline.sql"] = render_flink_job(pipeline)
        files["flink/sql/postgres_tables.sql"] = render_postgres_tables(pipeline)
    return files
