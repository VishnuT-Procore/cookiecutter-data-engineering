"""Snowflake plugin generator: Kafka connector config plus dbt sources, bronze and silver models.

Called by scripts/generate.py; see that file for the plugin contract.
"""

from __future__ import annotations

import json

HEADER = "GENERATED by scripts/generate.py from config/pipeline.yml. Do not edit; change the config and run `make generate`."

MANAGED_GLOBS = ["dbt/models/bronze/*", "dbt/models/silver/*", "ingestion/connector.json"]

# Kafka Connect FileConfigProvider: secrets stay in a properties file on the Connect workers.
SECRETS = "${file:/opt/kafka/secrets/snowflake.properties:%s}"


def _jinja_list(items: list[str]) -> str:
    return "[" + ", ".join(repr(i) for i in items) + "]"


def _jinja_columns(columns: list[dict]) -> str:
    lines = [f"        {{'name': {c['name']!r}, 'type': {c['type']!r}}}" for c in columns]
    return "[\n" + ",\n".join(lines) + "\n    ]"


def _yaml_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_bronze(entity: dict, payload_format: str) -> str:
    return f"""-- {HEADER}
-- Bronze: every change from topic `{entity['topic']}`, append-only and idempotent on (partition, offset).
{{{{ config(unique_key=['_kafka_partition', '_kafka_offset']) }}}}

{{{{ bronze_model(
    source_table={entity['name']!r},
    payload_format={payload_format!r},
    columns={_jinja_columns(entity['columns'])}
) }}}}
"""


def render_silver(entity: dict) -> str:
    return f"""-- {HEADER}
-- Silver: latest version of each {entity['name']} row (deletes kept as _is_deleted = true).
{{{{ config(unique_key={_jinja_list(entity['primary_key'])}) }}}}

{{{{ silver_model(
    bronze_relation=ref('bronze_{entity['name']}'),
    columns={_jinja_columns(entity['columns'])},
    primary_key={_jinja_list(entity['primary_key'])},
    sequence_by={_jinja_list(entity['sequence_by'])}
) }}}}
"""


def render_sources(pipeline: dict) -> str:
    lines = [
        f"# {HEADER}",
        "version: 2",
        "",
        "sources:",
        "  - name: kafka_raw",
        f"    schema: {pipeline['raw_schema']}",
        "    description: Raw Kafka records landed by the Snowflake Kafka Connector (one table per topic).",
        "    tables:",
    ]
    for e in pipeline["entities"]:
        lines += [
            f"      - name: {e['name']}",
            f"        description: {_yaml_str('Raw records from Kafka topic ' + e['topic'] + '.')}",
            "        config:",
            "          meta:",
            f"            topic: {_yaml_str(e['topic'])}",
        ]
    return "\n".join(lines) + "\n"


def _column_docs(entity: dict, indent: str, pk_tests: bool) -> list[str]:
    lines = [f"{indent}columns:"]
    for c in entity["columns"]:
        lines.append(f"{indent}  - name: {c['name']}")
        if c["description"]:
            lines.append(f"{indent}    description: {_yaml_str(c['description'])}")
        if pk_tests and c["name"] in entity["primary_key"]:
            lines.append(f"{indent}    data_tests: [not_null]")
    return lines


def render_schema(pipeline: dict, layer: str) -> str:
    lines = [f"# {HEADER}", "version: 2", "", "models:"]
    for e in pipeline["entities"]:
        if layer == "bronze":
            desc = f"Change log of {e['name']} ({pipeline['payload_format']} payloads). {e['description']}".strip()
            key = ["_kafka_partition", "_kafka_offset"]
        else:
            desc = f"Latest version of each {e['name']} row. {e['description']}".strip()
            key = e["primary_key"]
        lines += [
            f"  - name: {layer}_{e['name']}",
            f"    description: {_yaml_str(desc)}",
            "    data_tests:",
            "      - unique_key_combination:",
            "          arguments:",
            f"            columns: {_jinja_list(key)}",
        ]
        lines += _column_docs(e, "    ", pk_tests=layer == "silver")
        lines.append("")
    return "\n".join(lines)


def raw_table_name(entity: dict) -> str:
    return entity["name"].upper()


def render_connector(pipeline: dict) -> str:
    entities = pipeline["entities"]
    config = {
        "connector.class": "com.snowflake.kafka.connector.SnowflakeSinkConnector",
        "tasks.max": "4",
        "topics": ",".join(e["topic"] for e in entities),
        "snowflake.topic2table.map": ",".join(f"{e['topic']}:{raw_table_name(e)}" for e in entities),
        "snowflake.ingestion.method": "SNOWPIPE_STREAMING",
        "snowflake.enable.schematization": "false",
        "snowflake.url.name": SECRETS % "url",
        "snowflake.user.name": SECRETS % "user",
        "snowflake.private.key": SECRETS % "private_key",
        "snowflake.private.key.passphrase": SECRETS % "private_key_passphrase",
        "snowflake.role.name": SECRETS % "role",
        "snowflake.database.name": SECRETS % "database",
        "snowflake.schema.name": pipeline["raw_schema"].upper(),
        "key.converter": "org.apache.kafka.connect.storage.StringConverter",
        "value.converter": "org.apache.kafka.connect.json.JsonConverter",
        "value.converter.schemas.enable": "false",
        "behavior.on.null.values": "DEFAULT",
        "buffer.flush.time": "10",
        "buffer.count.records": "10000",
        "buffer.size.bytes": "20000000",
        "errors.tolerance": "all",
        "errors.log.enable": "true",
        "errors.deadletterqueue.topic.name": f"{pipeline['project']}.dlq.snowflake",
        "errors.deadletterqueue.context.headers.enable": "true",
    }
    return json.dumps({"name": f"{pipeline['project']}-snowflake-sink", "config": config}, indent=2) + "\n"


def render(pipeline: dict) -> dict[str, str]:
    files = {
        "ingestion/connector.json": render_connector(pipeline),
        "dbt/models/bronze/_sources.yml": render_sources(pipeline),
        "dbt/models/bronze/_bronze.yml": render_schema(pipeline, "bronze"),
        "dbt/models/silver/_silver.yml": render_schema(pipeline, "silver"),
    }
    for e in pipeline["entities"]:
        files[f"dbt/models/bronze/bronze_{e['name']}.sql"] = render_bronze(e, pipeline["payload_format"])
        files[f"dbt/models/silver/silver_{e['name']}.sql"] = render_silver(e)
    return files
