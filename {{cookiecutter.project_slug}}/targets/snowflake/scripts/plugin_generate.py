"""Snowflake plugin generator: one Iceberg table per landing table, linked to the Iceberg REST catalog.

Called by scripts/generate.py.
"""

from __future__ import annotations

HEADER = "GENERATED by scripts/generate.py from config/pipeline.yml. Do not edit; change the config and run `make generate`."

MANAGED_GLOBS = ["snowflake/landing_tables.sql"]


def render(pipeline: dict) -> dict[str, str]:
    database = pipeline["project"].upper()
    schema = pipeline["landing_namespace"].upper()
    lines = [
        f"-- {HEADER}",
        "-- Exposes the Iceberg landing tables (written by Flink) to Snowflake. Run after snowflake/setup.sql,",
        "-- and again after adding entities. AUTO_REFRESH picks up new Iceberg commits.",
        "",
        f"CREATE SCHEMA IF NOT EXISTS {database}.{schema};",
    ]
    for e in pipeline["entities"]:
        lines += [
            "",
            f"CREATE ICEBERG TABLE IF NOT EXISTS {database}.{schema}.{e['name'].upper()}",
            f"  EXTERNAL_VOLUME = '{database}_LANDING_VOLUME'",
            f"  CATALOG = '{database}_LANDING_CATALOG'",
            f"  CATALOG_NAMESPACE = '{pipeline['landing_namespace']}'",
            f"  CATALOG_TABLE_NAME = '{e['name']}'",
            "  AUTO_REFRESH = TRUE;",
        ]
    lines += ["", f"GRANT SELECT ON ALL ICEBERG TABLES IN SCHEMA {database}.{schema} TO ROLE TRANSFORMER;", ""]
    return {"snowflake/landing_tables.sql": "\n".join(lines)}
