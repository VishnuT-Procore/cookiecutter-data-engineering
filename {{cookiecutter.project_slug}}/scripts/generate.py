#!/usr/bin/env python3
"""Validate config/pipeline.yml and (re)generate every file derived from it.

    python scripts/generate.py           # write generated files, remove stale ones
    python scripts/generate.py --check   # exit 1 if generated files are out of date (CI)

Generated (target-agnostic):
    ingestion/sql/landing.sql           Flink job: Kafka topics -> Iceberg landing tables (append-only)
    dbt/models/landing/_sources.yml     the landing tables as dbt sources
    dbt/models/bronze|silver/*          one bronze (change log) and silver (latest per key) model per entity

A target plugin may add files with scripts/plugin_generate.py, which defines
    MANAGED_GLOBS: list[str]   and   render(pipeline: dict) -> dict[str, str]
"""

from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CONFIG_PATH = ROOT / "config" / "pipeline.yml"
HEADER = "GENERATED by scripts/generate.py from config/pipeline.yml. Do not edit; change the config and run `make generate`."

IDENTIFIER = re.compile(r"^[a-z_][a-z0-9_]*$")
COLUMN_TYPE = re.compile(
    r"^(string|integer|bigint|double|boolean|date|timestamp|timestamp_ms|timestamp_us|decimal\(\d+,\d+\))$"
)
PAYLOAD_FORMATS = ("debezium", "json")
METADATA_COLUMNS = (
    "_op", "_is_deleted", "_source_ts_ms", "_kafka_topic", "_kafka_partition",
    "_kafka_offset", "_kafka_timestamp", "_ingested_at",
)
COMMON_MANAGED_GLOBS = [
    "ingestion/sql/*",
    "dbt/models/landing/*",
    "dbt/models/bronze/*",
    "dbt/models/silver/*",
]


class ConfigError(ValueError):
    pass


# --- config ------------------------------------------------------------------------------------

def load_pipeline(path: Path = CONFIG_PATH) -> dict:
    """Load and validate pipeline.yml, returning a normalized dict."""
    with open(path) as f:
        cfg = yaml.safe_load(f) or {}

    errors: list[str] = []
    for key in ("project", "target", "payload_format", "landing_namespace", "entities"):
        if key not in cfg:
            errors.append(f"missing top-level key '{key}'")
    if errors:
        raise ConfigError("; ".join(errors))
    if cfg["payload_format"] not in PAYLOAD_FORMATS:
        errors.append(f"payload_format must be one of {PAYLOAD_FORMATS}")
    if not IDENTIFIER.match(str(cfg["landing_namespace"])):
        errors.append(f"landing_namespace '{cfg['landing_namespace']}' is not a valid identifier")
    if not cfg["entities"]:
        errors.append("at least one entity is required")

    names, topics = set(), set()
    for i, entity in enumerate(cfg["entities"] or []):
        name = entity.get("name")
        if not name or not IDENTIFIER.match(name):
            errors.append(f"entities[{i}]: name '{name}' is not a valid identifier")
            continue
        where = f"entity '{name}'"
        if name in names:
            errors.append(f"{where}: duplicate name")
        names.add(name)
        topic = entity.get("topic")
        if not topic:
            errors.append(f"{where}: topic is required")
        elif topic in topics:
            errors.append(f"{where}: topic '{topic}' is used by another entity")
        topics.add(topic)

        columns = entity.get("columns") or []
        if not columns:
            errors.append(f"{where}: at least one column is required")
        col_names = []
        for col in columns:
            cname, ctype = col.get("name"), str(col.get("type", "")).replace(" ", "")
            if not cname or not IDENTIFIER.match(cname):
                errors.append(f"{where}: column name '{cname}' is not a valid identifier")
            elif cname in METADATA_COLUMNS:
                errors.append(f"{where}: column '{cname}' collides with a bronze metadata column")
            if not COLUMN_TYPE.match(ctype):
                errors.append(f"{where}: column '{cname}' has unsupported type '{col.get('type')}'")
            col["type"] = ctype
            col.setdefault("description", "")
            col_names.append(cname)
        if len(col_names) != len(set(col_names)):
            errors.append(f"{where}: duplicate column names")

        pk = entity.get("primary_key") or []
        if not pk:
            errors.append(f"{where}: primary_key is required")
        for key in pk:
            if key not in col_names:
                errors.append(f"{where}: primary_key column '{key}' is not in columns")
        entity.setdefault("description", "")

    if errors:
        raise ConfigError("invalid config/pipeline.yml:\n  - " + "\n  - ".join(errors))

    # Ordering that picks the latest change per key (most significant first).
    sequence = ["_source_ts_ms", "_kafka_offset"] if cfg["payload_format"] == "debezium" else ["_kafka_offset"]
    for entity in cfg["entities"]:
        entity["sequence_by"] = sequence
    return cfg


# --- Flink landing job -------------------------------------------------------------------------

def render_landing_sql(pipeline: dict) -> str:
    ns = pipeline["landing_namespace"]
    parts = [
        f"-- {HEADER}",
        "-- Kafka -> Iceberg landing, append-only: one table per topic with the raw key/value and Kafka metadata.",
        "-- ${...} placeholders are filled from the environment by ingestion/landing.py.",
        "",
        "SET 'pipeline.name' = '${FLINK_JOB_NAME}';",
        "-- Iceberg commits on every checkpoint: this interval is the landing freshness.",
        "SET 'execution.checkpointing.interval' = '${FLINK_CHECKPOINT_INTERVAL}';",
        "SET 'table.local-time-zone' = 'UTC';",
        "",
        "CREATE CATALOG lake WITH (",
        "  'type' = 'iceberg',",
        "  'catalog-type' = 'rest',",
        "  'uri' = '${ICEBERG_CATALOG_URI}',",
        "  'warehouse' = '${ICEBERG_WAREHOUSE}'${ICEBERG_CATALOG_OPTIONS}",
        ");",
        "",
        f"CREATE DATABASE IF NOT EXISTS lake.{ns};",
    ]
    inserts = []
    for e in pipeline["entities"]:
        name = e["name"]
        parts += [
            "",
            f"-- ===== {name} ({e['topic']}) =====",
            f"CREATE TABLE IF NOT EXISTS lake.{ns}.{name} (",
            "  kafka_topic STRING,",
            "  kafka_partition INT,",
            "  kafka_offset BIGINT,",
            "  kafka_timestamp TIMESTAMP_LTZ(3),",
            "  kafka_key STRING,",
            "  kafka_value STRING,",
            "  ingested_at TIMESTAMP_LTZ(3),",
            "  ingest_date DATE",
            ") PARTITIONED BY (ingest_date) WITH ('format-version' = '2');",
            "",
            f"CREATE TEMPORARY TABLE kafka_{name} (",
            "  kafka_key STRING,",
            "  kafka_value STRING,",
            "  kafka_topic STRING METADATA FROM 'topic' VIRTUAL,",
            "  kafka_partition INT METADATA FROM 'partition' VIRTUAL,",
            "  kafka_offset BIGINT METADATA FROM 'offset' VIRTUAL,",
            "  kafka_timestamp TIMESTAMP_LTZ(3) METADATA FROM 'timestamp' VIRTUAL",
            ") WITH (",
            "  'connector' = 'kafka',",
            f"  'topic' = '{e['topic']}',",
            "  'properties.bootstrap.servers' = '${FLINK_KAFKA_BOOTSTRAP_SERVERS}',",
            "  'properties.group.id' = '${FLINK_KAFKA_GROUP_ID}',",
            "  'properties.auto.offset.reset' = 'earliest',",
            "  'scan.startup.mode' = 'group-offsets',",
            "  'key.format' = 'raw',",
            "  'key.fields' = 'kafka_key',",
            "  'value.format' = 'raw',",
            "  'value.fields-include' = 'EXCEPT_KEY'${FLINK_KAFKA_OPTIONS}",
            ");",
        ]
        inserts.append(
            f"INSERT INTO lake.{ns}.{name}\n"
            "SELECT kafka_topic, kafka_partition, kafka_offset, kafka_timestamp, kafka_key, kafka_value,\n"
            "       CURRENT_TIMESTAMP, CAST(CURRENT_TIMESTAMP AS DATE)\n"
            f"FROM kafka_{name};"
        )
    parts += ["", "EXECUTE STATEMENT SET", "BEGIN", *inserts, "END;", ""]
    return "\n".join(parts)


# --- dbt ---------------------------------------------------------------------------------------

def _jinja_list(items: list[str]) -> str:
    return "[" + ", ".join(repr(i) for i in items) + "]"


def _jinja_columns(columns: list[dict]) -> str:
    lines = [f"        {{'name': {c['name']!r}, 'type': {c['type']!r}}}" for c in columns]
    return "[\n" + ",\n".join(lines) + "\n    ]"


def _yaml_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_bronze(entity: dict, payload_format: str) -> str:
    return f"""-- {HEADER}
-- Bronze: every change from topic `{entity['topic']}`, typed, append-only, idempotent on (partition, offset).
{{{{ config(unique_key=['_kafka_partition', '_kafka_offset']) }}}}

{{{{ bronze_model(
    source_table={entity['name']!r},
    payload_format={payload_format!r},
    columns={_jinja_columns(entity['columns'])}
) }}}}
"""


def render_silver(entity: dict) -> str:
    return f"""-- {HEADER}
-- Silver: latest version of each {entity['name']} row (deletes kept as _is_deleted = true).
{{{{ config(unique_key={_jinja_list(entity['primary_key'])}) }}}}

{{{{ silver_model(
    bronze_relation=ref('bronze_{entity['name']}'),
    columns={_jinja_columns(entity['columns'])},
    primary_key={_jinja_list(entity['primary_key'])},
    sequence_by={_jinja_list(entity['sequence_by'])}
) }}}}
"""


def render_sources(pipeline: dict) -> str:
    lines = [
        f"# {HEADER}",
        "version: 2",
        "",
        "sources:",
        "  - name: landing",
        "    # Where the target sees the Iceberg landing tables (LANDING_* variables in .env).",
        "    database: \"{{ env_var('LANDING_DATABASE', target.database) }}\"",
        f"    schema: \"{{{{ env_var('LANDING_SCHEMA', '{pipeline['landing_namespace']}') }}}}\"",
        "    description: Raw Kafka records landed in Apache Iceberg by the Flink job (ingestion/sql/landing.sql).",
        "    tables:",
    ]
    for e in pipeline["entities"]:
        lines += [
            f"      - name: {e['name']}",
            f"        identifier: \"{{{{ env_var('LANDING_TABLE_PREFIX', '') }}}}{e['name']}\"",
            f"        description: {_yaml_str('Raw records from Kafka topic ' + e['topic'] + '.')}",
            "        config:",
            "          meta:",
            f"            topic: {_yaml_str(e['topic'])}",
        ]
    return "\n".join(lines) + "\n"


def render_schema(pipeline: dict, layer: str) -> str:
    lines = [f"# {HEADER}", "version: 2", "", "models:"]
    for e in pipeline["entities"]:
        if layer == "bronze":
            desc = f"Change log of {e['name']} ({pipeline['payload_format']} payloads). {e['description']}".strip()
            key = ["_kafka_partition", "_kafka_offset"]
        else:
            desc = f"Latest version of each {e['name']} row. {e['description']}".strip()
            key = e["primary_key"]
        lines += [
            f"  - name: {layer}_{e['name']}",
            f"    description: {_yaml_str(desc)}",
            "    data_tests:",
            "      - unique_key_combination:",
            "          arguments:",
            f"            columns: {_jinja_list(key)}",
            "    columns:",
        ]
        for c in e["columns"]:
            lines.append(f"      - name: {c['name']}")
            if c["description"]:
                lines.append(f"        description: {_yaml_str(c['description'])}")
            if layer == "silver" and c["name"] in e["primary_key"]:
                lines.append("        data_tests: [not_null]")
        lines.append("")
    return "\n".join(lines)


def render_common(pipeline: dict) -> dict[str, str]:
    files = {
        "ingestion/sql/landing.sql": render_landing_sql(pipeline),
        "dbt/models/landing/_sources.yml": render_sources(pipeline),
        "dbt/models/bronze/_bronze.yml": render_schema(pipeline, "bronze"),
        "dbt/models/silver/_silver.yml": render_schema(pipeline, "silver"),
    }
    for e in pipeline["entities"]:
        files[f"dbt/models/bronze/bronze_{e['name']}.sql"] = render_bronze(e, pipeline["payload_format"])
        files[f"dbt/models/silver/silver_{e['name']}.sql"] = render_silver(e)
    return files


# --- driver ------------------------------------------------------------------------------------

def _load_plugin():
    path = ROOT / "scripts" / "plugin_generate.py"
    if not path.exists():
        return None
    sys.dont_write_bytecode = True  # keep the project tree free of __pycache__
    spec = importlib.util.spec_from_file_location("plugin_generate", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args(argv)

    try:
        pipeline = load_pipeline()
    except ConfigError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    rendered = render_common(pipeline)
    globs = list(COMMON_MANAGED_GLOBS)
    plugin = _load_plugin()
    if plugin is not None:
        rendered.update(plugin.render(pipeline))
        globs += plugin.MANAGED_GLOBS

    rendered = {Path(p): content for p, content in rendered.items()}
    existing = {p.relative_to(ROOT) for g in globs for p in ROOT.glob(g) if p.is_file()}
    stale = sorted(existing - set(rendered))
    changed = sorted(p for p, c in rendered.items() if not (ROOT / p).is_file() or (ROOT / p).read_text() != c)

    if args.check:
        if changed or stale:
            for p in changed:
                print(f"out of date: {p}", file=sys.stderr)
            for p in stale:
                print(f"stale:       {p}", file=sys.stderr)
            print("Run `make generate` and commit the result.", file=sys.stderr)
            return 1
        print("generated files are up to date")
        return 0

    for p in changed:
        (ROOT / p).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / p).write_text(rendered[p])
        print(f"wrote   {p}")
    for p in stale:
        (ROOT / p).unlink()
        print(f"removed {p}")
    if not changed and not stale:
        print("generated files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
